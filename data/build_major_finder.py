    def packable(count):
        return any((count - 4 * fours) % 3 == 0 for fours in range(count // 4, -1, -1)) if count else False

    def chunk_34(items):
        count = len(items)
        sizes = None
        for fours in range(count // 4, -1, -1):
            rem = count - 4 * fours
            if rem % 3 == 0:
                sizes = [4] * fours + [3] * (rem // 3)
                break
        if not sizes:
            raise SystemExit("cannot pack late choices: " + str(count))
        chunks, cursor = [], 0
        for size in sizes:
            chunks.append(items[cursor:cursor + size])
            cursor += size
        return chunks


def hierarchy_late(profiles):
    """계열분류 안의 전공만 한 문항으로 묶는다. 보기 하나는 전공 하나고, 빈 보기는 넣지 않는다."""
    grouped = {}
    for profile in profiles:
        grouped.setdefault((profile["track"], profile["mid"]), []).append(profile)
    questions = []
    for track, mid in sorted(grouped):
        members = sorted(grouped[(track, mid)], key=lambda profile: -profile["sortOrder"])
        slug = f"{TRACK_SLUG[track]}-{mid}"
        prompt = MID_PROMPTS.get(mid, f"{mid} 분야에서 하고 싶은 일은 무엇인가요?")
        for index, group in enumerate(chunk_even(members, 3)):
            suffix = "" if index == 0 else f"-{index + 1}"
            qid = f"lq-{slug}{suffix}"
            choices = []
            for number, profile in enumerate(group, start=1):
                label = SHORT_CHOICES[profile["name"]]
                choices.append(decorate({
                    "id": f"{qid}-{number}",
                    "label": label,
                    "coreMajorIds": [profile["majorId"]],
                    "relatedMajorIds": [],
                    "reason": label + "를 골랐어요.",
                    "special": False,
                }))
            choices.append({
                "id": f"{qid}-unknown",
                "label": "아직 잘 모르겠어요",
                "coreMajorIds": [],
                "relatedMajorIds": [],
                "reason": "",
                "special": True,
                "specialKind": "unknown",
            })
            questions.append({
                "id": qid,
                "diffId": f"diff-{slug}{suffix}",
                "prompt": prompt,
                "role": "split",
                "maxSelect": 1,
                "topicTags": [f"mid:{track}|{mid}", f"track:{track}"],
                "choices": choices,
            })
    return questions


def chunk_even(items, size=3):
    """한 문항의 실제 보기는 최대 3개. 남는 전공은 다음 문항으로 나눈다."""
    count = len(items)
    if count == 0:
        return []
    parts = max(1, (count + size - 1) // size)
    base, extra = divmod(count, parts)
    chunks = []
    cursor = 0
    for index in range(parts):
        take = base + (1 if index < extra else 0)
        chunks.append(items[cursor:cursor + take])
        cursor += take
    return chunks



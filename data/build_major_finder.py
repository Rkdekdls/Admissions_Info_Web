def normalize_late(questions, sort_by_id):
    """질문마다 실제 보기 3개와 아직 잘 모르겠어요. 전공 보기는 하나당 전공 하나다.

    같은 점수면 목록 앞의 전공이 이미 상위에 있으므로, 그런 전공을 마지막 문항에 둔다.
    뒤에 있는 전공이 먼저 질문되어 후반 점수를 받을 수 있다.
    """
    normalized = []
    for question in questions:
        real = [choice for choice in question["choices"] if not choice["special"]]
        unknown = next(choice for choice in question["choices"] if choice["special"])
        fills = list(FILL_CHOICES.get(question["id"], []))

        def sort_key(choice):
            majors = choice["coreMajorIds"] or choice["relatedMajorIds"]
            return -(sort_by_id.get(majors[0], 0) if majors else 0)

        ordered = sorted(real, key=sort_key)
        for index, group in enumerate(chunk_even(ordered, 3)):
            if not group or len(group) > 3:
                raise SystemExit("bad late chunk: " + question["id"])
            choices = []
            used = set()
            for choice in group:
                copied = dict(choice)
                copied["coreMajorIds"] = list(choice["coreMajorIds"])
                copied["relatedMajorIds"] = list(choice["relatedMajorIds"])
                choices.append(copied)
                used.add(copied["label"])
            host = next((choice["coreMajorIds"] or choice["relatedMajorIds"]) for choice in choices)
            while len(choices) < 3:
                if not fills:
                    raise SystemExit("need a fill choice: " + question["id"])
                label = fills.pop(0)
                if label in used:
                    raise SystemExit("duplicate fill label: " + label)
                used.add(label)
                choices.append({
                    "id": f"{question['id']}-fill-{index}-{len(choices)}",
                    "label": label,
                    "coreMajorIds": [],
                    "relatedMajorIds": list(host),
                    "reason": label + " 쪽을 골랐어요.",
                    "special": False,
                })
            suffix = "" if index == 0 else f"-{index + 1}"
            normalized.append({
                "id": question["id"] + suffix,
                "diffId": question["diffId"] + suffix,
                "prompt": question["prompt"],
                "role": question["role"],
                "topicTags": list(question["topicTags"]),
                "choices": choices + [dict(unknown, id=question["id"] + suffix + "-unknown")],
            })
        if fills:
            raise SystemExit("unused fill choices: " + question["id"])
    return normalized


def load_source():
    wb = openpyxl.load_workbook(XLSX, read_only=True, data_only=True)
    ws = wb.active
    rows = []
    for i, row in enumerate(ws.iter_rows(values_only=True), start=1):
        if i == 1:
            continue
        if not row or not row[2]:
            continue
        track = str(row[0]).strip()
        mid = str(row[1]).strip()
        name = str(row[2]).strip()
        key = f"{track}|{mid}|{name}"
        major_id = "mj-" + hashlib.sha256(key.encode("utf-8")).hexdigest()[:12]
        rows.append({
            "majorId": major_id,
            "name": name,
            "track": track,
            "mid": mid,
            "sortOrder": i,
            "sourceRow": i,
        })
    return rows


